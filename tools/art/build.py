"""pnpm art:build – builds public/assets from art/ (concept/16-asset-pipeline.md §2, §6).

python tools/art/build.py [--quality mid|high]

- FX and sprite sheets: copied losslessly (PNG). The 2D tile set in art/tiles is no longer built (3D board, D6).
- 3D models (art/models: export_models.py, tripo_units.py, blender_weapons.py in tools/art): copied as .glb.
- Ground textures for the 3D board: generated by tools/art/ground.py (needs NumPy).
- Portraits: WebP q85, 768 px high (high: 1152 px).
- Backgrounds: WebP q80, 1920×1080 (high: 2560×1440).
- Item images: WebP q85, 132 px square (high: 192 px).
- Heads (art/mockups/characters-s1/<id>.png): round-chibi head crop for the medallions of the battle HUD and the campaign view.
  The two avatar looks rhen_a|b: WebP q85, 160 px square. Other characters: WebP q70, 112 px square, only those that appear as units
  in content/units.yaml or a map (the rest ships with the act packages; initial-download budget).
- Season 1 locations (art/mockups/locations-s1): only those the app shell shows, WebP q75, 1280×720 (high: 1920×1080).
- Writes public/assets/manifest.json describing everything that exists.
Requires Pillow.
"""
import json
import os
import re
import shutil
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ground  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
ART = os.path.join(ROOT, 'art')
OUT = os.path.join(ROOT, 'public', 'assets')
HIGH = '--quality' in sys.argv and sys.argv[sys.argv.index('--quality') + 1] == 'high'
PORTRAIT_H = 1152 if HIGH else 768
BG_SIZE = (2560, 1440) if HIGH else (1920, 1080)
# season 1 places: portrait phones crop a landscape image, 1280 px is enough
LOCATION_SIZE = (1920, 1080) if HIGH else (1280, 720)
# only the places the app shell shows; the others ship with the act packages (Epic 7, initial-download budget)
SHELL_LOCATIONS = {'lager_unterwegs'}
# the two avatar looks of the new-campaign form (art/mockups/characters-s1/<id>.png)
AVATAR_LOOKS = ('rhen_a', 'rhen_b')
# head crop of the 1254 px portraits: square from the top; 160 px is a 52 px medallion at 3x
HEAD_CROP = (230, 0, 1030, 800)
AVATAR_PX = 160
# battle medallion: 78 px on the HUD, 56 px in the forecast; 112 px at q70 is ~4.5 KB per head
HEAD_PX = 112
# 44 px item image at 3x device pixels
ITEM_PX = 192 if HIGH else 132


def ensure(p):
    os.makedirs(p, exist_ok=True)
    return p


def copy_tree_files(src, dst, exts):
    out = []
    if not os.path.isdir(src):
        return out
    ensure(dst)
    for f in sorted(os.listdir(src)):
        if os.path.splitext(f)[1].lower() in exts and 'preview' not in f:
            shutil.copy2(os.path.join(src, f), os.path.join(dst, f))
            out.append(f)
    return out


def build_sheets(kind):
    base = os.path.join(ART, 'sprites', kind)
    result = {}
    if not os.path.isdir(base):
        return result
    for sid in sorted(os.listdir(base)):
        d = os.path.join(base, sid)
        meta = os.path.join(d, 'sheet.json')
        color = os.path.join(d, 'sheet.key.png')
        if not (os.path.isfile(meta) and os.path.isfile(color)):
            continue
        dst = ensure(os.path.join(OUT, 'sprites', kind, sid))
        shutil.copy2(color, os.path.join(dst, 'sheet.png'))
        has_normal = os.path.isfile(os.path.join(d, 'sheet.normal.png'))
        if has_normal:
            shutil.copy2(os.path.join(d, 'sheet.normal.png'), os.path.join(dst, 'normal.png'))
        with open(meta, encoding='utf-8') as f:
            m = json.load(f)
        m['normal'] = has_normal
        result[sid] = m
    return result


def build_models():
    """art/models/units/<id>.glb, art/models/props/<id>_<state>.glb and art/models/weapons/<id>.glb → public/assets/models."""
    result = {'units': [], 'props': {}, 'weapons': []}
    base = os.path.join(ART, 'models')
    for kind in ('units', 'props', 'weapons'):
        files = copy_tree_files(os.path.join(base, kind), os.path.join(OUT, 'models', kind), {'.glb'})
        for f in files:
            name = f[:-4]
            if kind in ('units', 'weapons'):
                result[kind].append(name)
            else:
                pid, _, state = name.partition('_')
                result['props'].setdefault(pid, []).append(state)
    return result


def build_portraits():
    base = os.path.join(ART, 'portraits')
    result = {}
    if not os.path.isdir(base):
        return result
    for pid in sorted(os.listdir(base)):
        d = os.path.join(base, pid)
        if not os.path.isdir(d):
            continue
        moods = []
        for f in sorted(os.listdir(d)):
            if not f.endswith('.png'):
                continue
            mood = f[:-4]
            im = Image.open(os.path.join(d, f)).convert('RGBA')
            w = round(im.width * PORTRAIT_H / im.height)
            im = im.resize((w, PORTRAIT_H), Image.LANCZOS)
            dst = ensure(os.path.join(OUT, 'portraits', pid))
            im.save(os.path.join(dst, f"{mood}.webp"), "WEBP", quality=85, method=4)
            moods.append(mood)
        result[pid] = moods
    return result


def build_backgrounds():
    base = os.path.join(ART, 'backgrounds')
    result = []
    if not os.path.isdir(base):
        return result
    dst = ensure(os.path.join(OUT, 'backgrounds'))
    for f in sorted(os.listdir(base)):
        if not f.endswith('.png'):
            continue
        im = Image.open(os.path.join(base, f)).convert('RGB').resize(BG_SIZE, Image.LANCZOS)
        im.save(os.path.join(dst, f[:-4] + '.webp'), 'WEBP', quality=80, method=4)
        result.append(f[:-4])
    return result


def build_locations():
    """art/mockups/locations-s1/<id>.png (season 1 places, candidates until Epic 8) → public/assets/locations/<id>.webp."""
    base = os.path.join(ART, 'mockups', 'locations-s1')
    result = []
    if not os.path.isdir(base):
        return result
    dst = ensure(os.path.join(OUT, 'locations'))
    for f in sorted(os.listdir(base)):
        if not f.endswith('.png') or f[:-4] not in SHELL_LOCATIONS:
            continue
        im = Image.open(os.path.join(base, f)).convert('RGB')
        im.thumbnail(LOCATION_SIZE, Image.LANCZOS)
        im.save(os.path.join(dst, f[:-4] + '.webp'), 'WEBP', quality=75, method=6)
        result.append(f[:-4])
    return result


def content_unit_ids():
    """Ids a board unit can have: every id/char/portrait value in content/units.yaml and content/maps (no YAML library needed)."""
    pat = re.compile(r'(?<![a-z0-9_])(?:id|char|portrait):[ 	]*([a-z0-9_]+)')
    content = os.path.join(ROOT, 'content')
    files = [os.path.join(content, 'units.yaml')]
    maps = os.path.join(content, 'maps')
    files += [os.path.join(maps, f) for f in sorted(os.listdir(maps)) if f.endswith('.yaml')]
    ids = set()
    for path in files:
        with open(path, encoding='utf-8') as f:
            ids.update(pat.findall(f.read()))
    return ids


def build_heads():
    """Round-chibi portraits → head crops public/assets/avatars/<id>.webp (clipped round by the UI); ids = unit ids."""
    base = os.path.join(ART, 'mockups', 'characters-s1')
    result = []
    if not os.path.isdir(base):
        return result
    dst = ensure(os.path.join(OUT, 'avatars'))
    wanted = content_unit_ids() | set(AVATAR_LOOKS)
    for f in sorted(os.listdir(base)):
        pid, ext = os.path.splitext(f)
        if ext != '.png' or pid not in wanted:
            continue
        im = Image.open(os.path.join(base, f)).convert('RGBA').crop(HEAD_CROP)
        if pid in AVATAR_LOOKS:
            im.resize((AVATAR_PX, AVATAR_PX), Image.LANCZOS).save(os.path.join(dst, pid + '.webp'), 'WEBP', quality=85, method=6)
        else:
            im.resize((HEAD_PX, HEAD_PX), Image.LANCZOS).save(os.path.join(dst, pid + '.webp'), 'WEBP', quality=70, alpha_quality=60, method=6)
        result.append(pid)
    return result


def build_items():
    """art/items/<id>.png (painted item images, 512 px) → public/assets/items/<id>.webp at ITEM_PX (DESIGN.md item-image)."""
    base = os.path.join(ART, 'items')
    result = []
    if not os.path.isdir(base):
        return result
    dst = ensure(os.path.join(OUT, 'items'))
    for f in sorted(os.listdir(base)):
        if not f.endswith('.png'):
            continue
        im = Image.open(os.path.join(base, f)).convert('RGBA').resize((ITEM_PX, ITEM_PX), Image.LANCZOS)
        im.save(os.path.join(dst, f[:-4] + '.webp'), 'WEBP', quality=85, method=4)
        result.append(f[:-4])
    return result


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    ensure(OUT)
    fx = copy_tree_files(os.path.join(ART, 'fx'), os.path.join(OUT, 'fx'), {'.png', '.json'})
    manifest = {
        'tileSize': 48,
        'fx': bool(fx),
        'units': build_sheets('units'),
        'models': build_models(),
        'ground': ground.build(os.path.join(OUT, 'ground')),
        'portraits': build_portraits(),
        'backgrounds': build_backgrounds(),
        'items': build_items(),
        'avatars': build_heads(),
        'locations': build_locations(),
    }
    audio_src = os.path.join(ROOT, 'audio-src', 'build')
    if os.path.isdir(audio_src):
        files = copy_tree_files(audio_src, os.path.join(OUT, 'audio'), {'.mp3', '.webm', '.m4a', '.ogg', '.json'})
        manifest['audio'] = sorted({os.path.splitext(f)[0] for f in files if not f.endswith('.json')})
    with open(os.path.join(OUT, 'manifest.json'), 'w', encoding='utf-8') as f:
        json.dump(manifest, f, indent=1)
    total = sum(os.path.getsize(os.path.join(dp, fn)) for dp, _, fns in os.walk(OUT) for fn in fns)
    print(f"assets: {len(manifest['units'])} units, {len(manifest['portraits'])} portraits, "
          f"{len(manifest['backgrounds'])} backgrounds, {len(manifest['models']['units'])} unit models, "
          f"{len(manifest['ground'])} ground textures – {total / 1e6:.1f} MB")


if __name__ == '__main__':
    main()
